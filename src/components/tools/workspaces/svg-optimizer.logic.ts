/**
 * Pure, string-only SVG cleanup. The input is never parsed as markup by a
 * browser, no script is executed and no network or storage API is touched.
 * A small quote-aware tokenizer keeps attributes and text nodes intact while
 * comments, editor metadata and redundant whitespace are removed.
 */

export const SVG_MAX_CHARS = 200_000;

export type SvgOptimizeErrorCode = "EMPTY" | "TOO_LARGE" | "NOT_SVG" | "UNBALANCED";

/** Typed error so the workspace can show its own translated, actionable text. */
export class SvgOptimizeError extends Error {
  readonly code: SvgOptimizeErrorCode;

  constructor(code: SvgOptimizeErrorCode) {
    super(code);
    this.name = "SvgOptimizeError";
    this.code = code;
  }
}

export interface SvgOptimizeOptions {
  removeComments: boolean;
  removeMetadata: boolean;
  collapseWhitespace: boolean;
  jsxAttributes: boolean;
}

export const DEFAULT_SVG_OPTIMIZE_OPTIONS: SvgOptimizeOptions = {
  removeComments: true,
  removeMetadata: true,
  collapseWhitespace: true,
  jsxAttributes: false,
};

export const SAMPLE_SVG =
  '<?xml version="1.0" encoding="UTF-8"?>\n' +
  '<!-- Sample icon from the Toolpika code desk -->\n' +
  '<svg xmlns="http://www.w3.org/2000/svg" width="64" height="64" viewBox="0 0 64 64">\n' +
  '  <metadata>Generated by a vector editor</metadata>\n' +
  '  <rect x="8" y="8" width="48" height="48" rx="12" fill="#5b4bff" />\n' +
  '  <path d="M20 32 L28 40 L44 24" fill="none" stroke="#ffffff" stroke-width="4" />\n' +
  '</svg>';

export interface SvgOptimizeResult {
  output: string;
  inputBytes: number;
  outputBytes: number;
  savedPercent: number;
  commentsRemoved: number;
  metadataRemoved: number;
}

/** Deterministic UTF-8 byte count without the browser TextEncoder API. */
export function byteLength(text: string): number {
  let bytes = 0;
  for (const character of text) {
    const point = character.codePointAt(0) ?? 0;
    if (point <= 0x7f) bytes += 1;
    else if (point <= 0x7ff) bytes += 2;
    else if (point <= 0xffff) bytes += 3;
    else bytes += 4;
  }
  return bytes;
}

type SvgToken = {
  kind: "tag" | "text" | "comment" | "cdata" | "directive";
  value: string;
};

function findTagEnd(source: string, from: number): number {
  let quote = "";
  for (let index = from; index < source.length; index += 1) {
    const character = source[index];
    if (quote) {
      if (character === quote) quote = "";
      continue;
    }
    if (character === '"' || character === "'") {
      quote = character;
      continue;
    }
    if (character === ">") return index + 1;
  }
  return source.length;
}

export function tokenizeSvg(source: string): SvgToken[] {
  const tokens: SvgToken[] = [];
  let cursor = 0;

  while (cursor < source.length) {
    if (source.startsWith("<!--", cursor)) {
      const end = source.indexOf("-->", cursor + 4);
      const stop = end === -1 ? source.length : end + 3;
      tokens.push({ kind: "comment", value: source.slice(cursor, stop) });
      cursor = stop;
      continue;
    }
    if (source.startsWith("<![CDATA[", cursor)) {
      const end = source.indexOf("]]>", cursor + 9);
      const stop = end === -1 ? source.length : end + 3;
      tokens.push({ kind: "cdata", value: source.slice(cursor, stop) });
      cursor = stop;
      continue;
    }
    if (source.startsWith("<?", cursor)) {
      const end = source.indexOf("?>", cursor + 2);
      const stop = end === -1 ? source.length : end + 2;
      tokens.push({ kind: "directive", value: source.slice(cursor, stop) });
      cursor = stop;
      continue;
    }
    if (source.startsWith("<!", cursor)) {
      const stop = findTagEnd(source, cursor + 2);
      tokens.push({ kind: "directive", value: source.slice(cursor, stop) });
      cursor = stop;
      continue;
    }
    if (source[cursor] === "<") {
      const stop = findTagEnd(source, cursor + 1);
      tokens.push({ kind: "tag", value: source.slice(cursor, stop) });
      cursor = stop;
      continue;
    }
    const next = source.indexOf("<", cursor);
    const stop = next === -1 ? source.length : next;
    tokens.push({ kind: "text", value: source.slice(cursor, stop) });
    cursor = stop;
  }

  return tokens;
}

function tagName(tag: string): string {
  const match = /^<\/?\s*([A-Za-z][\w.:-]*)/u.exec(tag);
  return match ? match[1].toLowerCase() : "";
}

function isSelfClosing(tag: string): boolean {
  return /\/\s*>$/u.test(tag);
}

/** Reject non-SVG and unbalanced input before any cleanup is attempted. */
export function validateSvg(input: string): void {
  if (!input.trim()) throw new SvgOptimizeError("EMPTY");
  if (byteLength(input) > SVG_MAX_CHARS) throw new SvgOptimizeError("TOO_LARGE");

  const tokens = tokenizeSvg(input);
  const root = tokens.find(
    (token) => token.kind === "tag" && tagName(token.value) === "svg",
  );
  if (!root) throw new SvgOptimizeError("NOT_SVG");

  const stack: string[] = [];
  for (const token of tokens) {
    if (token.kind !== "tag") continue;
    const name = tagName(token.value);
    if (!name) continue;
    if (token.value.startsWith("</")) {
      if (stack.pop() !== name) throw new SvgOptimizeError("UNBALANCED");
    } else if (!isSelfClosing(token.value)) {
      stack.push(name);
    }
  }
  if (stack.length > 0) throw new SvgOptimizeError("UNBALANCED");
}

const DROP_ELEMENTS = new Set(["metadata", "title", "desc"]);

const EDITOR_ATTRIBUTE =
  /(?:\s)(?:xmlns:(?:sodipodi|inkscape|sketch|adobe)|(?:sodipodi|inkscape|sketch|adobe):[A-Za-z][\w:-]*)\s*=\s*(?:"[^"]*"|'[^']*')/giu;

function stripEditorAttributes(tag: string): string {
  return tag.replace(EDITOR_ATTRIBUTE, "");
}

const JSX_RENAMES: Record<string, string> = {
  class: "className",
  for: "htmlFor",
  tabindex: "tabIndex",
  "xml:space": "xmlSpace",
};

function jsxAttributeName(name: string): string {
  const exact = JSX_RENAMES[name.toLowerCase()];
  if (exact) return exact;
  if (name.includes(":")) {
    const parts = name.split(":");
    const tail = parts[parts.length - 1] ?? "";
    return `${parts.slice(0, -1).join("")}${tail.charAt(0).toUpperCase()}${tail.slice(1)}`;
  }
  return name.replace(/-([a-z])/gu, (_, letter: string) => letter.toUpperCase());
}

/** Rename attributes outside quoted values only, so path data stays untouched. */
function convertAttributesToJsx(tag: string): string {
  let output = "";
  let quote = "";
  let cursor = 0;

  while (cursor < tag.length) {
    const character = tag[cursor];
    if (quote) {
      output += character;
      if (character === quote) quote = "";
      cursor += 1;
      continue;
    }
    if (character === '"' || character === "'") {
      quote = character;
      output += character;
      cursor += 1;
      continue;
    }
    if (/[A-Za-z]/u.test(character) && (cursor === 0 || /\s/u.test(tag[cursor - 1]))) {
      let end = cursor;
      while (end < tag.length && /[\w.:-]/u.test(tag[end])) end += 1;
      const name = tag.slice(cursor, end);
      let after = end;
      while (after < tag.length && /\s/u.test(tag[after])) after += 1;
      if (tag[after] === "=") {
        output += jsxAttributeName(name);
        cursor = end;
        continue;
      }
      output += name;
      cursor = end;
      continue;
    }
    output += character;
    cursor += 1;
  }

  return output;
}

function collapseTagWhitespace(tag: string): string {
  let output = "";
  let quote = "";
  let pending = false;

  for (const character of tag) {
    if (quote) {
      output += character;
      if (character === quote) quote = "";
      continue;
    }
    if (character === '"' || character === "'") {
      if (pending && output && !/\s$/u.test(output)) output += " ";
      pending = false;
      quote = character;
      output += character;
      continue;
    }
    if (/\s/u.test(character)) {
      pending = true;
      continue;
    }
    if (
      pending &&
      character !== ">" &&
      character !== "/" &&
      output &&
      !/[\s<]$/u.test(output)
    ) {
      output += " ";
    }
    pending = false;
    output += character;
  }

  return output;
}

export function optimizeSvg(
  input: string,
  options: SvgOptimizeOptions,
): SvgOptimizeResult {
  validateSvg(input);

  const tokens = tokenizeSvg(input);
  const kept: SvgToken[] = [];
  let commentsRemoved = 0;
  let metadataRemoved = 0;
  let skipName = "";
  let skipDepth = 0;

  for (const token of tokens) {
    if (skipDepth > 0) {
      if (token.kind === "tag") {
        const name = tagName(token.value);
        if (name === skipName) {
          if (token.value.startsWith("</")) skipDepth -= 1;
          else if (!isSelfClosing(token.value)) skipDepth += 1;
        }
      }
      continue;
    }

    if (token.kind === "comment") {
      if (options.removeComments) {
        commentsRemoved += 1;
        continue;
      }
      kept.push(token);
      continue;
    }

    if (token.kind === "tag") {
      const name = tagName(token.value);
      if (
        options.removeMetadata &&
        DROP_ELEMENTS.has(name) &&
        !token.value.startsWith("</")
      ) {
        metadataRemoved += 1;
        if (isSelfClosing(token.value)) continue;
        skipName = name;
        skipDepth = 1;
        continue;
      }
      let value = token.value;
      if (options.removeMetadata) value = stripEditorAttributes(value);
      if (options.jsxAttributes) value = convertAttributesToJsx(value);
      if (options.collapseWhitespace) value = collapseTagWhitespace(value);
      kept.push({ kind: token.kind, value });
      continue;
    }

    if (token.kind === "text") {
      if (!token.value.trim()) continue;
      const value = options.collapseWhitespace
        ? token.value.replace(/\s+/gu, " ").trim()
        : token.value;
      kept.push({ kind: token.kind, value });
      continue;
    }

    kept.push(token);
  }

  const output = kept.map((token) => token.value).join("").trim();
  const inputBytes = byteLength(input);
  const outputBytes = byteLength(output);
  const savedPercent = inputBytes > 0
    ? Math.max(0, Math.round(((inputBytes - outputBytes) / inputBytes) * 100))
    : 0;

  return {
    output,
    inputBytes,
    outputBytes,
    savedPercent,
    commentsRemoved,
    metadataRemoved,
  };
}
